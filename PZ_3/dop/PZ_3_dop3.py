'''
Ввести двухзначное число. Если сумма цифр числа четная,
то увеличить число на 2, в противном случае уменьшить на 2.
'''

num = int(input("Введите двузначное число: "))
if num < 10 or num > 99:
    print("Вводите двузначное число!!")
else:
    tens, units = divmod(num, 10)
    if (tens + units) % 2 == 0:
        print(num + 2)
    else:
        print(num - 2)